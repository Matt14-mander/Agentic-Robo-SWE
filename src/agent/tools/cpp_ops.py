"""Optional external-workspace C++ tools (never enabled in read-only sessions)."""

import json

from langchain_core.tools import tool

from agent.cpp import build_root, compilation_database, configure_build, require_workspace, semantic_query


def _render(action):
    try:
        value = json.dumps(action(), ensure_ascii=False)
        return value if len(value) <= 24000 else value[:24000] + "\n[output truncated]"
    except (OSError, ValueError, RuntimeError) as exc:
        return f"ERROR: {exc}"


@tool
def cpp_build(target: str = "all", configure_only: bool = False) -> str:
    """Configure root CMake project with Ninja and export compile_commands; optionally build target.

    Uses the session's pinned container or explicitly trusted local toolchain. No shell command input.
    Build timeout is 180 seconds per stage. Failed compilation returns diagnostics.
    """
    return _render(lambda: configure_build(target, configure_only))


@tool
def cpp_compile_commands() -> str:
    """Inspect compilation database generated by cpp_build; does not execute recorded commands."""
    return _render(lambda: compilation_database(build_root(require_workspace()) / "compile_commands.json"))


@tool
def cpp_semantic_query(path: str, operation: str, line: int = 1, column: int = 1) -> str:
    """Query clangd: definition, references, hover (type), or diagnostics.

    Input line/column are 1-based Unicode character positions. Returned locations follow LSP
    (zero-based UTF-16). Requires cpp_build configuration; references cover up to 32 opened TUs.
    """
    return _render(lambda: semantic_query(path, operation, line, column))


CPP_TOOLS = [cpp_build, cpp_compile_commands, cpp_semantic_query]
